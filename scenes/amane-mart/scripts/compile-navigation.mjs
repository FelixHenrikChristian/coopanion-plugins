import {writeFile} from 'node:fs/promises';
import {getNavigationData} from '../src/navigation-data.js';
import {createNavigationQuery} from '../src/navigation-query.js';

const layout=getNavigationData(),query=createNavigationQuery(layout),step=layout.cellSize;
const x0=Math.ceil((layout.bounds.minX-layout.gridOrigin[0])/step)*step+layout.gridOrigin[0];
const z0=Math.ceil((layout.bounds.minZ-layout.gridOrigin[1])/step)*step+layout.gridOrigin[1];
const nx=Math.floor((layout.bounds.maxX-x0)/step)+1,nz=Math.floor((layout.bounds.maxZ-z0)/step)+1;
const valid=new Uint8Array(nx*nz),parent=new Int32Array(nx*nz);parent.fill(-1);
const point=i=>{const x=+(x0+Math.floor(i/nz)*step).toFixed(5),z=+(z0+(i%nz)*step).toFixed(5);return [x,query.surfaceAt(x,z)?.y??0,z];};
for(let i=0;i<valid.length;i++){const p=point(i);valid[i]=+query.isWalkable(p[0],p[2]);}
function closest(p){
  let result=-1,best=Infinity;
  for(let dx=-3;dx<=3;dx++)for(let dz=-3;dz<=3;dz++){
    const x=Math.round((p[0]-x0)/step)+dx,z=Math.round((p[2]-z0)/step)+dz;
    if(x<0||x>=nx||z<0||z>=nz)continue;
    const i=x*nz+z;if(!valid[i])continue;
    const other=point(i),distance=Math.hypot(other[0]-p[0],other[2]-p[2]);
    if(distance<best&&query.segmentWalkable(p,other)){result=i;best=distance;}
  }
  if(result<0)throw Error('Unreachable exact station '+JSON.stringify(p));return result;
}
const start=closest(layout.spawn),queue=[start];parent[start]=start;
for(let head=0;head<queue.length;head++){
  const i=queue[head],x=Math.floor(i/nz),z=i%nz;
  for(const [dx,dz] of [[1,0],[-1,0],[0,1],[0,-1]]){
    const xx=x+dx,zz=z+dz;if(xx<0||xx>=nx||zz<0||zz>=nz)continue;
    const j=xx*nz+zz;if(!valid[j]||parent[j]!==-1)continue;
    if(!query.segmentWalkable(point(i),point(j)))continue;
    parent[j]=i;queue.push(j);
  }
}
const nodes=[{id:'spawn',position:layout.spawn}],edges=[],edgeKeys=new Set();
function addNode(p,id){
  const found=nodes.find(n=>n.position.every((v,i)=>Math.abs(v-p[i])<1e-6));
  if(found&&!id)return found.id;
  const entry={id:id??'junction:'+nodes.length,position:p};nodes.push(entry);return entry.id;
}
function edge(from,to){
  if(from===to)return;const k=[from,to].sort().join('|');if(edgeKeys.has(k))return;
  const a=nodes.find(n=>n.id===from),b=nodes.find(n=>n.id===to);
  if(!query.segmentWalkable(a.position,b.position))throw Error('Unsafe edge '+k);
  edgeKeys.add(k);edges.push({from,to,cost:+Math.hypot(...a.position.map((v,i)=>v-b.position[i])).toFixed(6)});
}
for(const item of layout.items){
  const goal=closest(item.position);if(parent[goal]===-1)throw Error('No route to '+item.id);
  const chain=[];for(let i=goal;i!==start;i=parent[i])chain.push(point(i));chain.push(point(start));chain.reverse();
  const path=[layout.spawn,...chain,item.position];let from='spawn';
  for(let i=0;i<path.length-1;){
    let next=i+1;
    for(let j=path.length-1;j>i+1;j--)if(query.segmentWalkable(path[i],path[j])){next=j;break;}
    const to=addNode(path[next],next===path.length-1?'item:'+item.id:undefined);edge(from,to);from=to;i=next;
  }
}
for(let i=0;i<nodes.length;i++)for(let j=i+1;j<nodes.length;j++){
  if(query.segmentWalkable(nodes[i].position,nodes[j].position))edge(nodes[i].id,nodes[j].id);
}
await writeFile(new URL('../src/navigation-graph.js',import.meta.url),
  '// Generated by scripts/compile-navigation.mjs; every edge sweeps the full agent radius.\n'+
  'export const navigation = '+JSON.stringify({nodes,edges},null,2)+';\n');
console.log(JSON.stringify({targets:layout.items.length,reachableCells:queue.length,nodes:nodes.length,edges:edges.length}));
